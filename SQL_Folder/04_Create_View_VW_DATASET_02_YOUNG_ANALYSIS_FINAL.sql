CREATE OR REPLACE VIEW VW_DATASET_02_YOUNG_ANALYSIS_FINAL AS
  WITH TAB_CHILD AS (
  SELECT 
            RB030 AS ID,
            RX030 AS ID_FAMILY,
            CASE WHEN RB090 = 1 THEN 0 ELSE 1 END AS FEMALE,
            CASE WHEN HB120 >= 6 THEN 6 ELSE HB120 END AS MEMBER,
RB080 AS YEAR
,2023-RB080 as AGE--: YEAR OF BIRTH
,CASE WHEN PE010 = 1 THEN 1 ELSE 0 END AS STUDENT-- Participation in formal education and training (student or apprentice): [1] Yes; [2] No
,CASE WHEN PL040A BETWEEN 1 AND 3 THEN 1 ELSE 0 END AS EMPL -- Status in employment (main job) -- [1] Self-employed with employees [2] Self-employed without employees [3] Employee [4] Family worker (unpaid)
--,PL051A -- Occupation in main job (ISCO-08 COM)
,CASE WHEN PL025 = 1 THEN 1 ELSE 0 END AS AVL_FOR_WORK-- Available for work: [1] Yes; [2] No
,CASE WHEN PL020 = 1 THEN 1 ELSE 0 END AS LOOKING_FOR_JOB-- Actively looking for a job: [1] Yes; [2] No
,HY020 AS TOT_DISPOSABLE_HH_INC
,RB220 AS FATHER
,RB230 AS MOTHER
--,HX060
,CASE WHEN HX060 IN ('10','11','12') OR (HX060 = '13' AND RB220 IS NOT NULL AND RB230 IS NOT NULL) THEN 1 ELSE 0 END AS COUPLE
--,HB120
,CASE WHEN HX060 IN ('10','11','12') OR (HX060 = '13' AND RB220 IS NOT NULL AND RB230 IS NOT NULL) THEN HB120 - 3 ELSE HB120 - 2 END AS BROTHERS
FROM TD_UDB_cIT23R
	left outer join td_udb_cit23p
	on RB030 = PB030
		left outer join td_udb_cit23h
		on RX030 = HB030
WHERE RX030 IN (
                select DB030 from TD_UDB_cIT23D
                where DB040 = 'ITC' AND DB100 = 1
            )
        AND RB080 BETWEEN 1998 AND 2006
        AND (RB220 IS NOT NULL OR RB230 IS NOT NULL)
)

SELECT 
    TAB_CHILD."ID",TAB_CHILD."ID_FAMILY",TAB_CHILD."FEMALE",TAB_CHILD."MEMBER",TAB_CHILD."YEAR",TAB_CHILD."AGE",TAB_CHILD."STUDENT",TAB_CHILD."EMPL",TAB_CHILD."AVL_FOR_WORK",TAB_CHILD."LOOKING_FOR_JOB",TAB_CHILD."TOT_DISPOSABLE_HH_INC",TAB_CHILD."FATHER",TAB_CHILD."MOTHER",TAB_CHILD."COUPLE",TAB_CHILD."BROTHERS"
    ,CASE WHEN MOM.pe041>=300 AND MOM.pe041<=500 AND 2023 - MOM.PB140 BETWEEN 25 AND 64 AND MOM.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS SECONDARY_MOM
    ,CASE WHEN MOM.pe041>=400 AND MOM.pe041<=500 AND 2023 - MOM.PB140 BETWEEN 25 AND 39 AND MOM.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS TERTIARY_MOM
    ,CASE WHEN DAD.pe041>=300 AND DAD.pe041<=500 AND 2023 - DAD.PB140 BETWEEN 25 AND 64 AND DAD.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS SECONDARY_DAD
    ,CASE WHEN DAD.pe041>=400 AND DAD.pe041<=500 AND 2023 - DAD.PB140 BETWEEN 25 AND 39 AND DAD.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS TERTIARY_DAD
    ,MOM.PL040A AS MAIN_JOB_MOM -- [1] Self-employed with employees [2] Self-employed without employees [3] Employee [4] Family worker (unpaid)
    ,DAD.PL040A AS MAIN_JOB_DAD -- [1] Self-employed with employees [2] Self-employed without employees [3] Employee [4] Family worker (unpaid)

FROM TAB_CHILD

    LEFT OUTER JOIN td_udb_cit23p MOM
    ON MOM.PB030 = MOTHER

        LEFT OUTER JOIN td_udb_cit23p DAD
        ON DAD.PB030 = FATHER;

