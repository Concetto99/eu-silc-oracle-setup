CREATE OR REPLACE VIEW VW_DATASET_01_CHILDREN_ANALYSIS_FINAL AS 
  WITH TAB_CHILD AS (
  SELECT 
            RB030 AS ID,
            RX030 AS ID_FAMILY,
            CASE WHEN RB090 = 1 THEN 0 ELSE 1 END AS FEMALE,
            CASE WHEN HB120 >= 6 THEN 6 ELSE HB120 END AS MEMBER,
            /*CASE WHEN 
            2023 - RB080 <= 15 THEN 1 
            WHEN 
            2023 - RB080 > 15 AND 2023 - RB080 <= 24 THEN 2
            WHEN 
            2023 - RB080 > 24 AND 2023 - RB080 <= 44 THEN 3 
            WHEN 
            2023 - RB080 > 44 AND 2023 - RB080 <= 64 THEN 4
            ELSE 5 
            END AS AGE_CLASS,*/
            --CASE WHEN pe041>=300 AND pe041<=500 AND 2023 - RB080 BETWEEN 25 AND 64 THEN 1 ELSE 0 END  AS SECONDARY,
            --CASE WHEN pe041>=400 AND pe041<=500 AND 2023 - RB080 BETWEEN 25 AND 39 THEN 1 ELSE 0 END  AS TERTIARY,
RB080 AS YEAR
,2023-RB080 as AGE--: YEAR OF BIRTH
,RL010 AS EDU_PRE_SCHOOL
,RL020 AS EDU_COMPULSORY_SCHOOL
,RL030 AS CHDCRE_CENTRE_BASED_SERVICES
,RL040 AS CHDCRE_DAY_CARE_CENTRE
,RL050 AS CHDCRE_PROFESSIONAL_CHILD_MINDER_HOME
,RL060 AS CHDCRE_GRAND_PARENTS_OTH_HH_MEMBERS_NEIGH
--,HY010 AS TOT_HH_GROSS_INC
,HY020 AS TOT_DISPOSABLE_HH_INC
,HY050N AS FAMILY_CHILDREN_RELATED_ALLOWANCES
,RB220 AS FATHER
,RB230 AS MOTHER
--,HX060
,CASE WHEN HX060 IN ('10','11','12') OR (HX060 = '13' AND RB220 IS NOT NULL AND RB230 IS NOT NULL) THEN 1 ELSE 0 END AS COUPLE
--,HB120
,CASE WHEN HX060 IN ('10','11','12') OR (HX060 = '13' AND RB220 IS NOT NULL AND RB230 IS NOT NULL) THEN HB120 - 3 ELSE HB120 - 2 END AS BROTHERS
FROM TD_UDB_cIT23R
	left outer join td_udb_cit23p
	on RB030 = PB030
		left outer join td_udb_cit23h
		on RX030 = HB030
WHERE RX030 IN (
                select DB030 from TD_UDB_cIT23D
                where DB040 = 'ITC' AND DB100 = 1
            )
        AND RB080 BETWEEN 2017 AND 2022
)

SELECT 
    TAB_CHILD."ID",TAB_CHILD."ID_FAMILY",TAB_CHILD."FEMALE",TAB_CHILD."MEMBER",TAB_CHILD."YEAR",TAB_CHILD."AGE",TAB_CHILD."EDU_PRE_SCHOOL",TAB_CHILD."EDU_COMPULSORY_SCHOOL",TAB_CHILD."CHDCRE_CENTRE_BASED_SERVICES",TAB_CHILD."CHDCRE_DAY_CARE_CENTRE",TAB_CHILD."CHDCRE_PROFESSIONAL_CHILD_MINDER_HOME",TAB_CHILD."CHDCRE_GRAND_PARENTS_OTH_HH_MEMBERS_NEIGH",TAB_CHILD."TOT_DISPOSABLE_HH_INC",TAB_CHILD."FAMILY_CHILDREN_RELATED_ALLOWANCES",TAB_CHILD."FATHER",TAB_CHILD."MOTHER",TAB_CHILD."COUPLE",TAB_CHILD."BROTHERS"
    ,CASE WHEN MOM.pe041>=300 AND MOM.pe041<=500 AND 2023 - MOM.PB140 BETWEEN 25 AND 64 AND MOM.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS SECONDARY_MOM
    ,CASE WHEN DAD.pe041>=300 AND DAD.pe041<=500 AND 2023 - DAD.PB140 BETWEEN 25 AND 64 AND DAD.pe041 IS NOT NULL THEN 1 ELSE 0 END  AS SECONDARY_DAD
    ,MOM.PL040A AS MAIN_JOB_MOM -- [1] Self-employed with employees [2] Self-employed without employees [3] Employee [4] Family worker (unpaid)
    ,DAD.PL040A AS MAIN_JOB_DAD -- [1] Self-employed with employees [2] Self-employed without employees [3] Employee [4] Family worker (unpaid)

FROM TAB_CHILD

    LEFT OUTER JOIN td_udb_cit23p MOM
    ON MOM.PB030 = MOTHER

        LEFT OUTER JOIN td_udb_cit23p DAD
        ON DAD.PB030 = FATHER;